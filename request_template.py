def build_request_docx(html, title, brand, logo_path, generated, upload_dir=""):
    doc = Document()
    normal = doc.styles["Normal"]
    normal.font.name, normal.font.size = FONT, Pt(10.5)
    normal.element.rPr.rFonts.set(qn("w:eastAsia"), FONT)
    for name in ("Heading 1", "Heading 2"):
        doc.styles[name].font.name = FONT

    sec = doc.sections[0]
    sec.page_width, sec.page_height = Mm(210), Mm(297)
    sec.top_margin, sec.bottom_margin = Mm(18), Mm(18)
    sec.left_margin = sec.right_margin = Mm(18)

    hp = sec.header.paragraphs[0]
    r = hp.add_run("%s · %s" % (brand, title))
    r.font.size, r.font.color.rgb = Pt(8), MUTED
    fp = sec.footer.paragraphs[0]
    fp.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    r = fp.add_run("Стр. ")
    r.font.size, r.font.color.rgb = Pt(8), MUTED
    add_field(fp, "PAGE")
    r = fp.add_run(" из ")
    r.font.size, r.font.color.rgb = Pt(8), MUTED
    add_field(fp, "NUMPAGES")

    # title block: logo + brand, title, gradient bar, date
    p = doc.add_paragraph()
    if os.path.exists(logo_path):
        p.add_run().add_picture(logo_path, width=Mm(9))
        p.add_run("  ")
    r = p.add_run(brand)
    r.bold, r.font.size, r.font.color.rgb = True, Pt(15), BRAND
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(10)
    r = p.add_run(title)
    r.bold, r.font.size = True, Pt(20)
    bar = doc.add_table(rows=1, cols=len(GRADIENT))
    no_borders(bar)
    set_widths(bar, [174.0 / len(GRADIENT)] * len(GRADIENT))
    for i, color in enumerate(GRADIENT):
        cell = bar.cell(0, i)
        shade(cell, color)
        cp = cell.paragraphs[0]
        cp.paragraph_format.space_after = Pt(0)
        cp.add_run().font.size = Pt(2)
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(6)
    r = p.add_run("Версия шаблона от %s" % generated)
    r.font.size, r.font.color.rgb = Pt(9), MUTED

    # body: <h3> become numbered section headings, everything else goes through the report renderer
    R = Renderer(doc, {"figure": "Рисунок"}, upload_dir=upload_dir)
    chunk = []

    def flush():
        if chunk:
            R.blocks(doc, chunk)
            chunk.clear()

    for n in parse_html(html).children:
        if not isinstance(n, str) and n.tag == "h3":
            flush()
            heading(doc, text_of(n).strip(), level=1)
        else:
            chunk.append(n)
    flush()
    return doc
