def _table(head, rows, empty_rows=0):
    cols = len(head)
    out = ["<table><thead><tr>", "".join("<th>%s</th>" % h for h in head), "</tr></thead><tbody>"]
    for r in rows:
        r = list(r) + [""] * (cols - len(r))
        out.append("<tr>" + "".join("<td>%s</td>" % c for c in r) + "</tr>")
    for _ in range(empty_rows):
        out.append("<tr>" + "<td></td>" * cols + "</tr>")
    out.append("</tbody></table>")
    return "".join(out)


def _qa(rows):
    """Two-column table: question → empty answer cell."""
    return _table(["Вопрос", "Ответ"], [(q, "") for q in rows])


def _checks(items):
    return "<ul>" + "".join("<li>%s %s</li>" % (BOX, i) for i in items) + "</ul>"


